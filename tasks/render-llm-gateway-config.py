#!/usr/bin/env python3
"""render-llm-gateway-config.py — validate gateway.yml and render the gateway files.

Reads the user-owned routing configuration (``gateway.yml``) and the gateway
secret file (``/srv/llm-gateway/.env``) and writes three deterministic files:

  config.yaml         LiteLLM model groups, routing and affinity settings
  compose.ports.yml   explicit host bindings (never a wildcard)
  firewall.sh         idempotent DOCKER-USER source filter (UFW cannot see
                      Docker-published ports)

The renderer never writes a secret into a generated file: the LiteLLM config
holds ``os.environ/NAME`` references only. It collects every validation error
in one run and writes nothing when any check fails.

Import this module directly from tests (the file name contains hyphens)::

    spec = importlib.util.spec_from_file_location("renderer", path)
"""

from __future__ import annotations

import argparse
import ipaddress
import os
import re
import sys
import tempfile
from pathlib import Path
from urllib.parse import urlparse

import yaml

DEFAULT_PORT = 4000
DEFAULT_AFFINITY_TTL = 7200
DEFAULT_REQUEST_TIMEOUT = 1200

ALLOWED_TOP_LEVEL = {
    "version",
    "listen",
    "affinity_ttl_seconds",
    "request_timeout_seconds",
    "backends",
    "models",
}
ALLOWED_LISTEN = {"port", "addresses", "allow_from"}
ALLOWED_BACKEND = {"base_url", "api_key_env", "best_effort"}
ALLOWED_MODEL = {"name", "aliases", "deployments"}
ALLOWED_DEPLOYMENT = {
    "backend",
    "model",
    "id",
    "max_parallel",
    "weight",
    "order",
    "resident",
}

MODEL_NAME_RE = re.compile(r"^[A-Za-z0-9._/-]+$")
BACKEND_NAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]*$")
ENV_NAME_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

CONFIG_HEADER = (
    "# Generated by tasks/render-llm-gateway-config.py — do not edit.\n"
    "# Source: gateway.yml (validated on every render).\n\n"
)
PORTS_HEADER = (
    "# Generated by tasks/render-llm-gateway-config.py — do not edit.\n"
    "# Explicit host bindings only: no 0.0.0.0 and no ::, ever.\n"
)
FIREWALL_HEADER = (
    "#!/usr/bin/env bash\n"
    "# Generated by tasks/render-llm-gateway-config.py — do not edit.\n"
    "#\n"
    "# Source filter for the Docker-published gateway port. UFW does not see\n"
    "# Docker's published ports, so the allow-list lives in DOCKER-USER. Docker\n"
    "# re-creates its own chains on restart; llm-gateway-firewall.service runs\n"
    "# this script after every docker.service start.\n"
)


class ValidationError(Exception):
    """One or more validation failures; ``messages`` carries every line."""

    def __init__(self, messages: list[str]):
        self.messages = messages
        super().__init__("; ".join(messages))


class _StrictLoader(yaml.SafeLoader):
    """SafeLoader that rejects duplicate mapping keys instead of silently
    keeping the last one."""


class _IndentedDumper(yaml.SafeDumper):
    """SafeDumper that indents sequences under their parent key."""

    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


def _construct_mapping(loader, node, deep=False):
    loader.flatten_mapping(node)
    mapping = {}
    for key_node, value_node in node.value:
        key = loader.construct_object(key_node, deep=deep)
        if key in mapping:
            raise yaml.constructor.ConstructorError(
                "while constructing a mapping",
                node.start_mark,
                f"found duplicate key {key!r}",
                key_node.start_mark,
            )
        mapping[key] = loader.construct_object(value_node, deep=deep)
    return mapping


_StrictLoader.add_constructor(
    yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG, _construct_mapping
)


def _path(prefix: str, key: object) -> str:
    return f"{prefix}.{key}" if prefix else str(key)


def _is_int(value: object) -> bool:
    # bool is a subclass of int; YAML `true` must not pass as `1`.
    return isinstance(value, int) and not isinstance(value, bool)


def _reject_unknown(
    mapping: dict, allowed: set[str], prefix: str, errors: list[str]
) -> None:
    for key in sorted((set(mapping) - allowed), key=str):
        errors.append(f"{_path(prefix, key)}: unknown key")


def _mapping(value: object, path: str, errors: list[str]) -> dict:
    if not isinstance(value, dict):
        errors.append(f"{path}: expected a mapping")
        return {}
    return value


def _string_list(value: object, path: str, errors: list[str]) -> list[str]:
    if not isinstance(value, list):
        errors.append(f"{path}: expected a list")
        return []
    return value


def parse_env_file(path: Path) -> dict[str, str]:
    """Parse a dotenv file without evaluating it. Last occurrence wins."""
    values: dict[str, str] = {}
    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        values[key.strip()] = value.strip()
    return values


def load_config(path: Path) -> dict:
    """Load gateway.yml strictly (duplicate keys are an error)."""
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise ValidationError([f"{path}: cannot read gateway.yml ({exc})"]) from exc
    try:
        data = yaml.load(text, Loader=_StrictLoader)
    except yaml.YAMLError as exc:
        mark = getattr(exc, "problem_mark", None)
        where = f" at line {mark.line + 1}, column {mark.column + 1}" if mark else ""
        problem = getattr(exc, "problem", None) or str(exc)
        raise ValidationError([f"{path}: invalid YAML{where}: {problem}"]) from exc
    if not isinstance(data, dict):
        raise ValidationError([f"{path}: top level must be a mapping"])
    return data


def _validate_listen(data: dict, errors: list[str]) -> dict:
    listen = _mapping(data.get("listen"), "listen", errors)
    _reject_unknown(listen, ALLOWED_LISTEN, "listen", errors)

    port = listen.get("port", DEFAULT_PORT)
    if not _is_int(port) or not 1 <= port <= 65535:
        errors.append(f"listen.port: must be an integer in 1-65535 (got {port!r})")

    raw_addresses = listen.get("addresses")
    addresses: list[str] = []
    if not isinstance(raw_addresses, list) or not raw_addresses:
        errors.append("listen.addresses: must be a non-empty list of IPv4 addresses")
    else:
        seen: set[str] = set()
        for index, item in enumerate(raw_addresses):
            path = f"listen.addresses[{index}]"
            if not isinstance(item, str):
                errors.append(f"{path}: must be an IPv4 address string")
                continue
            try:
                address = ipaddress.IPv4Address(item)
            except ipaddress.AddressValueError:
                errors.append(f"{path}: '{item}' is not a valid IPv4 address (IPv6 is out of scope)")
                continue
            normalized = str(address)
            if address.is_unspecified:
                errors.append(
                    f"{path}: '{item}' is a wildcard address; list explicit private addresses"
                )
                continue
            if normalized in seen:
                errors.append(f"{path}: duplicate address '{normalized}'")
                continue
            seen.add(normalized)
            addresses.append(normalized)

    raw_allow = listen.get("allow_from")
    allow_from: list[str] = []
    if not isinstance(raw_allow, list) or not raw_allow:
        errors.append("listen.allow_from: must be a non-empty list of IPv4 CIDRs")
    else:
        seen_networks: set[str] = set()
        for index, item in enumerate(raw_allow):
            path = f"listen.allow_from[{index}]"
            if not isinstance(item, str):
                errors.append(f"{path}: must be an IPv4 CIDR string")
                continue
            try:
                network = ipaddress.IPv4Network(item, strict=False)
            except (ipaddress.AddressValueError, ValueError):
                errors.append(f"{path}: '{item}' is not a valid IPv4 CIDR")
                continue
            normalized = str(network)
            if network.prefixlen == 0:
                errors.append(
                    f"{path}: '{item}' is the default route; list explicit source networks"
                )
                continue
            if normalized in seen_networks:
                errors.append(f"{path}: duplicate network '{normalized}'")
                continue
            seen_networks.add(normalized)
            allow_from.append(normalized)

    return {"port": port, "addresses": addresses, "allow_from": allow_from}


def _validate_backends(data: dict, errors: list[str]) -> dict:
    raw_backends = data.get("backends")
    if not isinstance(raw_backends, dict) or not raw_backends:
        errors.append("backends: must be a non-empty mapping")
        return {}
    backends: dict[str, dict] = {}
    for name, raw in raw_backends.items():
        path = f"backends.{name}"
        if not isinstance(name, str) or not BACKEND_NAME_RE.match(name):
            errors.append(
                f"{path}: backend name must match [A-Za-z0-9][A-Za-z0-9_.-]*"
            )
        backend = _mapping(raw, path, errors)
        _reject_unknown(backend, ALLOWED_BACKEND, path, errors)

        base_url = backend.get("base_url")
        if not isinstance(base_url, str) or not base_url:
            errors.append(f"{path}.base_url: required (for example http://host:9292/v1)")
            base_url = ""
        else:
            parsed = urlparse(base_url)
            if (
                parsed.scheme not in ("http", "https")
                or not parsed.netloc
                or parsed.username is not None
                or parsed.password is not None
                or parsed.query
                or parsed.fragment
            ):
                errors.append(
                    f"{path}.base_url: '{base_url}' must be an http(s) URL with no "
                    "credentials, query or fragment"
                )

        api_key_env = backend.get("api_key_env")
        if api_key_env is not None:
            if not isinstance(api_key_env, str) or not ENV_NAME_RE.match(api_key_env):
                errors.append(
                    f"{path}.api_key_env: must match [A-Za-z_][A-Za-z0-9_]*"
                )
                api_key_env = ""
        else:
            api_key_env = ""

        best_effort = backend.get("best_effort", False)
        if not isinstance(best_effort, bool):
            errors.append(f"{path}.best_effort: must be a boolean")
            best_effort = False

        backends[name] = {
            "base_url": base_url,
            "api_key_env": api_key_env,
            "best_effort": best_effort,
        }
    return backends


def _validate_models(
    data: dict, backends: dict, errors: list[str], warnings: list[str]
) -> list[dict]:
    raw_models = data.get("models")
    if not isinstance(raw_models, list) or not raw_models:
        errors.append("models: must be a non-empty list")
        return []

    models: list[dict] = []
    public_names: list[str] = []
    aliases_seen: dict[str, str] = {}
    deployment_ids: dict[str, str] = {}

    for model_index, raw_model in enumerate(raw_models):
        model_path = f"models[{model_index}]"
        model = _mapping(raw_model, model_path, errors)
        _reject_unknown(model, ALLOWED_MODEL, model_path, errors)

        name = model.get("name")
        if not isinstance(name, str) or not MODEL_NAME_RE.match(name):
            errors.append(
                f"{model_path}.name: required and must match [A-Za-z0-9._/-]+"
            )
            name = ""
        elif name in public_names:
            errors.append(f"{model_path}.name: duplicate public model name '{name}'")
        else:
            public_names.append(name)

        raw_aliases = model.get("aliases", [])
        aliases = _string_list(raw_aliases, f"{model_path}.aliases", errors)
        clean_aliases: list[str] = []
        for alias_index, alias in enumerate(aliases):
            alias_path = f"{model_path}.aliases[{alias_index}]"
            if not isinstance(alias, str) or not alias:
                errors.append(f"{alias_path}: must be a non-empty string")
                continue
            if alias in aliases_seen:
                errors.append(
                    f"{alias_path}: duplicate alias '{alias}' "
                    f"(also used by model '{aliases_seen[alias]}')"
                )
                continue
            aliases_seen[alias] = name
            clean_aliases.append(alias)

        raw_deployments = model.get("deployments")
        if not isinstance(raw_deployments, list) or not raw_deployments:
            errors.append(f"{model_path}.deployments: must be a non-empty list")
            continue

        deployments: list[dict] = []
        for dep_index, raw_dep in enumerate(raw_deployments):
            dep_path = f"{model_path}.deployments[{dep_index}]"
            dep = _mapping(raw_dep, dep_path, errors)
            _reject_unknown(dep, ALLOWED_DEPLOYMENT, dep_path, errors)

            backend_name = dep.get("backend")
            if not isinstance(backend_name, str) or not backend_name:
                errors.append(f"{dep_path}.backend: required")
                backend_name = ""
            elif backend_name not in backends:
                errors.append(
                    f"{dep_path}.backend: unknown backend '{backend_name}' "
                    f"(configured: {', '.join(sorted(backends)) or 'none'})"
                )

            upstream_model = dep.get("model")
            if not isinstance(upstream_model, str) or not upstream_model:
                errors.append(f"{dep_path}.model: required (the box's llama-swap model id)")
                upstream_model = ""

            deployment_id = dep.get("id")
            if deployment_id is None:
                deployment_id = f"{backend_name}-{upstream_model}"
            elif not isinstance(deployment_id, str) or not deployment_id:
                errors.append(f"{dep_path}.id: must be a non-empty string")
                deployment_id = f"{backend_name}-{upstream_model}"
            if deployment_id in deployment_ids:
                errors.append(
                    f"{dep_path}.id: duplicate deployment id '{deployment_id}' "
                    f"(also used by '{deployment_ids[deployment_id]}')"
                )
            else:
                deployment_ids[deployment_id] = dep_path

            max_parallel = dep.get("max_parallel", 1)
            if not _is_int(max_parallel) or max_parallel < 1:
                errors.append(f"{dep_path}.max_parallel: must be an integer >= 1")
                max_parallel = 1

            weight = dep.get("weight", 1)
            if not _is_int(weight) or weight < 1:
                errors.append(f"{dep_path}.weight: must be an integer >= 1")
                weight = 1

            order = dep.get("order", 1)
            if not _is_int(order) or order < 1:
                errors.append(f"{dep_path}.order: must be an integer >= 1")
                order = 1
            backend = backends.get(backend_name, {})
            if backend.get("best_effort") and "order" not in dep:
                # best_effort means failover-only: order 2 receives no new
                # sessions while an order 1 deployment is healthy (C1).
                order = 2

            resident = dep.get("resident", True)
            if not isinstance(resident, bool):
                errors.append(f"{dep_path}.resident: must be a boolean")
                resident = True

            if backend.get("best_effort") and "order" in dep and dep["order"] == 1:
                errors.append(
                    f"{dep_path}.order: backend '{backend_name}' is best_effort, "
                    "which means order 2 (failover only); omit order or use a value > 1"
                )
            if order > 1 and weight > 1:
                warnings.append(
                    f"{dep_path}: order {order} with weight {weight} — weight is "
                    "ignored above order 1 (failover-only tier)"
                )

            deployments.append(
                {
                    "backend": backend_name,
                    "model": upstream_model,
                    "id": deployment_id,
                    "max_parallel": max_parallel,
                    "weight": weight,
                    "order": order,
                    "resident": resident,
                }
            )

        if len(deployments) > 1:
            for dep_index, dep in enumerate(deployments):
                if not dep["resident"]:
                    errors.append(
                        f"{model_path}.deployments[{dep_index}].resident: a shared "
                        "group (more than one deployment) requires resident: true on "
                        "every deployment (D5)"
                    )

        models.append({"name": name, "aliases": clean_aliases, "deployments": deployments})

    # Aliases may not shadow a public name.
    for alias, owner in aliases_seen.items():
        if alias in public_names:
            errors.append(
                f"models: alias '{alias}' (model '{owner}') collides with a public model name"
            )

    # A backend in both a shared group and a single-deployment model can evict
    # the resident model when the single-box model loads (C11).
    shared_backends: set[str] = set()
    single_backends: set[str] = set()
    for model in models:
        backends_used = {dep["backend"] for dep in model["deployments"]}
        if len(model["deployments"]) > 1:
            shared_backends |= backends_used
        else:
            single_backends |= backends_used
    for backend_name in sorted(shared_backends & single_backends):
        warnings.append(
            f"backends.{backend_name}: appears in a shared group and in a "
            "single-deployment model — running the single-box model there can evict "
            "the resident shared model (C11)"
        )

    # An alias equal to an upstream model id is legal but easy to misread.
    upstream_ids = {
        dep["model"] for model in models for dep in model["deployments"]
    }
    for alias, owner in aliases_seen.items():
        if alias in upstream_ids:
            warnings.append(
                f"models: alias '{alias}' (model '{owner}') equals an upstream model "
                "id; the public name and the backend id would look identical"
            )

    return models


def validate_config(
    data: dict, *, env_values: dict[str, str] | None = None, env_path: Path | None = None
) -> tuple[dict, list[str]]:
    """Validate *data* and return ``(normalized, warnings)``.

    Raises :class:`ValidationError` carrying every problem found. When
    ``env_values`` is given, every referenced ``api_key_env`` must exist and be
    non-empty there.
    """
    errors: list[str] = []
    warnings: list[str] = []

    _reject_unknown(data, ALLOWED_TOP_LEVEL, "", errors)

    if data.get("version") != 1 or not _is_int(data.get("version")):
        errors.append(f"version: must be 1 (got {data.get('version')!r})")

    listen = _validate_listen(data, errors)
    backends = _validate_backends(data, errors)
    models = _validate_models(data, backends, errors, warnings)

    affinity_ttl = data.get("affinity_ttl_seconds", DEFAULT_AFFINITY_TTL)
    if not _is_int(affinity_ttl) or affinity_ttl < 1:
        errors.append("affinity_ttl_seconds: must be an integer >= 1")
        affinity_ttl = DEFAULT_AFFINITY_TTL

    request_timeout = data.get("request_timeout_seconds", DEFAULT_REQUEST_TIMEOUT)
    if not _is_int(request_timeout) or request_timeout < 1:
        errors.append("request_timeout_seconds: must be an integer >= 1")
        request_timeout = DEFAULT_REQUEST_TIMEOUT

    if env_values is not None:
        missing: list[str] = []
        for backend_name in sorted(backends):
            env_name = backends[backend_name]["api_key_env"]
            if env_name and not env_values.get(env_name, ""):
                missing.append(env_name)
        if missing:
            where = f" in {env_path}" if env_path else ""
            for env_name in sorted(set(missing)):
                errors.append(
                    f"api_key_env '{env_name}' is missing or empty{where}; "
                    f"add a line: {env_name}=sk-..."
                )

    if errors:
        raise ValidationError(errors)

    normalized = {
        "port": listen["port"],
        "addresses": listen["addresses"],
        "allow_from": listen["allow_from"],
        "affinity_ttl_seconds": affinity_ttl,
        "request_timeout_seconds": request_timeout,
        "backends": backends,
        "models": models,
    }
    return normalized, warnings


def build_litellm_config(config: dict) -> dict:
    """Build the deterministic LiteLLM document from a validated config."""
    model_list = []
    for model in config["models"]:
        for deployment in model["deployments"]:
            backend = config["backends"][deployment["backend"]]
            params: dict = {
                "model": f"openai/{deployment['model']}",
                "api_base": backend["base_url"],
            }
            if backend["api_key_env"]:
                params["api_key"] = f"os.environ/{backend['api_key_env']}"
            params["max_parallel_requests"] = deployment["max_parallel"]
            params["weight"] = deployment["weight"]
            params["order"] = deployment["order"]
            params["timeout"] = config["request_timeout_seconds"]
            params["stream_timeout"] = config["request_timeout_seconds"]
            model_list.append(
                {
                    "model_name": model["name"],
                    "litellm_params": params,
                    "model_info": {"id": deployment["id"]},
                }
            )

    router_settings: dict = {
        "routing_strategy": "simple-shuffle",
        "optional_pre_call_checks": ["session_affinity"],
        "deployment_affinity_ttl_seconds": config["affinity_ttl_seconds"],
        "num_retries": 2,
        "allowed_fails": 3,
        "cooldown_time": 30,
        # Accepted by v1.106.6; verified in P0 (open question 6).
        "enable_weighted_failover": True,
        "session_affinity_repin_on_failover": True,
    }
    aliases = {
        alias: model["name"] for model in config["models"] for alias in model["aliases"]
    }
    if aliases:
        router_settings["model_group_alias"] = aliases

    return {
        "model_list": model_list,
        "router_settings": router_settings,
        "general_settings": {
            "master_key": "os.environ/LITELLM_MASTER_KEY",
            # C7: a background health check would issue a completion against
            # llama-swap, loading (and possibly swapping) a model.
            "background_health_checks": False,
        },
        "litellm_settings": {"turn_off_message_logging": True},
    }


def render_config_yaml(config: dict) -> str:
    body = yaml.dump(
        build_litellm_config(config),
        Dumper=_IndentedDumper,
        sort_keys=False,
        default_flow_style=False,
        allow_unicode=True,
        width=4096,
    )
    return CONFIG_HEADER + body


def render_compose_ports(config: dict) -> str:
    port = config["port"]
    lines = [
        PORTS_HEADER.rstrip("\n"),
        "services:",
        "  llm-gateway:",
        "    ports:",
    ]
    for address in config["addresses"]:
        lines.append(f'      - "{address}:{port}:{port}"')
    return "\n".join(lines) + "\n"


def render_firewall_script(config: dict) -> str:
    port = config["port"]
    cidrs = "\n".join(f'  "{cidr}"' for cidr in config["allow_from"])
    return (
        FIREWALL_HEADER
        + 'set -euo pipefail\n\n'
        + 'CHAIN="KWISATZ-LLM-GATEWAY"\n'
        + f'PORT="{port}"\n'
        + "ALLOW_FROM=(\n"
        + cidrs
        + "\n)\n\n"
        + 'if ! iptables -S DOCKER-USER >/dev/null 2>&1; then\n'
        + '  echo "ERROR: DOCKER-USER chain not found — enable Docker iptables management." >&2\n'
        + "  exit 1\n"
        + "fi\n\n"
        + 'iptables -N "$CHAIN" 2>/dev/null || true\n'
        + 'iptables -F "$CHAIN"\n'
        + 'iptables -A "$CHAIN" -m conntrack --ctstate ESTABLISHED,RELATED -j RETURN\n'
        + 'for cidr in "${ALLOW_FROM[@]}"; do\n'
        + '  iptables -A "$CHAIN" -s "$cidr" -p tcp --dport "$PORT" -j RETURN\n'
        + "done\n"
        + 'iptables -A "$CHAIN" -p tcp --dport "$PORT" -j DROP\n'
        + 'iptables -A "$CHAIN" -j RETURN\n\n'
        + "# Exactly one jump, at the head so a pre-existing ACCEPT cannot shadow it.\n"
        + 'while iptables -D DOCKER-USER -j "$CHAIN" 2>/dev/null; do :; done\n'
        + 'iptables -I DOCKER-USER 1 -j "$CHAIN"\n'
    )


def _write_atomic(path: Path, text: str, mode: int) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(text)
        os.chmod(tmp_name, mode)
        os.replace(tmp_name, path)
        os.chmod(path, mode)
    finally:
        if os.path.exists(tmp_name):
            os.unlink(tmp_name)


def render_files(config: dict, out_dir: Path) -> dict[Path, str]:
    """Return ``{path: text}`` for every rendered file, without writing."""
    return {
        out_dir / "config.yaml": render_config_yaml(config),
        out_dir / "compose.ports.yml": render_compose_ports(config),
        out_dir / "firewall.sh": render_firewall_script(config),
    }


def write_files(files: dict[Path, str]) -> None:
    for path, text in files.items():
        mode = 0o755 if path.suffix == ".sh" else 0o644
        _write_atomic(path, text, mode)


def _print_plan(config: dict) -> None:
    print(f"port\t{config['port']}")
    for address in config["addresses"]:
        print(f"address\t{address}")
    for cidr in config["allow_from"]:
        print(f"allow_from\t{cidr}")
    for name in sorted(config["backends"]):
        backend = config["backends"][name]
        best_effort = "true" if backend["best_effort"] else "false"
        print(f"backend\t{name}\t{backend['base_url']}\t{backend['api_key_env']}\t{best_effort}")
    for model in config["models"]:
        print(f"model\t{model['name']}\t{len(model['deployments'])}")
        for deployment in model["deployments"]:
            resident = "true" if deployment["resident"] else "false"
            print(
                f"deployment\t{model['name']}\t{deployment['id']}\t"
                f"{deployment['backend']}\t{deployment['order']}\t{resident}"
            )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="render-llm-gateway-config.py",
        description="Validate gateway.yml and render the LiteLLM gateway files.",
    )
    parser.add_argument("--config", required=True, type=Path, help="path to gateway.yml")
    parser.add_argument("--env-file", type=Path, help="gateway .env (required to render)")
    parser.add_argument("--out-dir", type=Path, help="directory for generated files")
    parser.add_argument(
        "--port",
        type=int,
        help="effective port; must equal listen.port when given",
    )
    parser.add_argument(
        "--print-port",
        action="store_true",
        help="print only the effective port from listen.port and exit",
    )
    parser.add_argument(
        "--print-plan",
        action="store_true",
        help="print the validated routing plan as tab-separated records and exit",
    )
    parser.add_argument(
        "--print-addresses",
        action="store_true",
        help="print one validated listen address per line and exit",
    )
    parser.add_argument(
        "--exclude-address",
        action="append",
        default=[],
        metavar="ADDR",
        help="skip this listen address (missing interface); repeatable",
    )
    args = parser.parse_args(argv)

    if sum((args.print_port, args.print_plan, args.print_addresses)) > 1:
        print("ERROR: choose only one --print-* mode", file=sys.stderr)
        return 1

    try:
        data = load_config(args.config)
        if args.print_port or args.print_plan or args.print_addresses:
            config, warnings = validate_config(data)
        else:
            if args.env_file is None or args.out_dir is None:
                print(
                    "ERROR: rendering requires --env-file and --out-dir "
                    "(or use --print-port / --print-plan)",
                    file=sys.stderr,
                )
                return 1
            if not args.env_file.is_file():
                raise ValidationError(
                    [f"{args.env_file}: secret file not found; run setup-llm-gateway.sh first"]
                )
            env_values = parse_env_file(args.env_file)
            config, warnings = validate_config(
                data, env_values=env_values, env_path=args.env_file
            )
    except ValidationError as exc:
        for message in exc.messages:
            print(f"ERROR: {message}", file=sys.stderr)
        return 1

    for warning in warnings:
        print(f"WARNING: {warning}", file=sys.stderr)

    if args.print_port:
        print(config["port"])
        return 0
    if args.print_addresses:
        for address in config["addresses"]:
            print(address)
        return 0
    if args.print_plan:
        _print_plan(config)
        return 0

    if args.port is not None and args.port != config["port"]:
        print(
            f"ERROR: --port {args.port} does not match listen.port {config['port']}",
            file=sys.stderr,
        )
        return 1

    excluded = set(args.exclude_address)
    if excluded:
        config = dict(config)
        config["addresses"] = [
            address for address in config["addresses"] if address not in excluded
        ]
        if not config["addresses"]:
            print(
                "ERROR: every listen address was excluded — nothing left to publish",
                file=sys.stderr,
            )
            return 1

    files = render_files(config, args.out_dir)
    try:
        write_files(files)
    except OSError as exc:
        print(f"ERROR: cannot write rendered files in {args.out_dir}: {exc}", file=sys.stderr)
        return 1

    for path in files:
        print(f"rendered: {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
